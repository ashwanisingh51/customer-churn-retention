GRAINS={
"customers_clean":"One customer at the reporting cutoff; latest telemetry for active customers or at cancellation.",
"monthly_snapshots":"One customer and calendar month with subscription exposure, including cancellation month; no rows after cancellation.",
"customer_segments":"One customer at cutoff, with mutually exclusive segment and current-risk attributes.",
"customer_risk_scores":"One customer at cutoff and nine auditable risk components; risk is null for churned customers.",
"monthly_churn_kpis":"One calendar month; opening base, flows and closing stocks.",
"monthly_retention_kpis":"One calendar month; retention of opening customers and renewal events.",
"cohort_retention":"One subscription-start cohort month and age 0-23; future outcomes are null.",
"plan_performance":"One plan; cumulative customer outcomes and current MRR.",
"channel_performance":"One acquisition channel; cumulative outcomes and current MRR.",
"geography_performance":"One region; cumulative outcomes and current MRR.",
"revenue_churn_impact":"One calendar month; normalized MRR bridge and prorated recognized revenue.",
"support_usage_analysis":"One latest-observation support-ticket band and usage band; descriptive cumulative outcomes.",
"churn_driver_associations":"One driver and category; prior-month exposure linked to next-month cancellations. Different drivers reuse exposures.",
"retention_by_dimension":"One dimension and category; fixed age-6 retention for mature acquisition cohorts only."}

def export(bucket="customer-churn-retention-analytics",prefix="quicksight"):
    if not re.fullmatch(r"[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]",bucket):
        raise ValueError("Use a valid S3 bucket name.")
    if not re.fullmatch(r"[A-Za-z0-9_/-]+",prefix) or ".." in prefix:
        raise ValueError("Use a simple S3 prefix.")
    prefix=prefix.strip("/")
    contracts={}
    ddl=["-- Generated by python -m scripts.export_analytics_data --bucket YOUR_BUCKET",
         "-- Run statements separately in Athena. STRING staging avoids CSV ISO-date/null parsing errors.",
         "CREATE DATABASE IF NOT EXISTS churn_retention;"]
    dictionary=["# Data dictionary\n", "All data are synthetic. Reporting cutoff: 2026-08-31. Currency: USD. Rates and discounts are fractions 0-1. Dates are ISO YYYY-MM-DD. Null means unavailable, unobserved or inapplicable, never an inferred zero.\n",
                "Detailed metric and segmentation definitions: [METRIC_DEFINITIONS.md](METRIC_DEFINITIONS.md).\n"]
    for path in sorted((ROOT/"data/processed").glob("*.csv")):
        name=path.stem
        frame=pd.read_csv(path)
        columns=[]
        for col in frame:
            dtype="date" if col in DATE_COLUMNS else "bigint" if pd.api.types.is_integer_dtype(frame[col]) else "double" if pd.api.types.is_numeric_dtype(frame[col]) else "varchar"
            if col=="risk_score" or col.startswith("risk_") and col not in ["risk_band"]:
                dtype="bigint"
            columns.append({"name":col,"type":dtype,"nullable":bool(frame[col].isna().any())})
        key=f"{prefix}/{name}/{name}.csv"
        contracts[name]={"grain":GRAINS[name],"primary_key":KEYS[name],"rows":len(frame),"s3_key":key,"columns":columns}
        staging=",\n  ".join(f"\x60{x['name']}\x60 STRING" for x in columns)
        ddl.append(f"CREATE EXTERNAL TABLE IF NOT EXISTS churn_retention.{name}_csv (\n  {staging}\n)\nROW FORMAT SERDE 'org.apache.hadoop.hive.serde2.OpenCSVSerde'\nWITH SERDEPROPERTIES ('separatorChar'=',', 'quoteChar'='\"', 'escapeChar'='\\\\')\nSTORED AS TEXTFILE\nLOCATION 's3://{bucket}/{prefix}/{name}/'\nTBLPROPERTIES ('skip.header.line.count'='1');")
        casts=[]
        for x in columns:
            col=x["name"]; dtype=x["type"]
            # Nullable integer-valued CSV columns may serialize as 42.00000000.
            expr=f'CAST(CAST(NULLIF("{col}", \'\') AS DOUBLE) AS BIGINT)' if dtype=="bigint" else f'CAST(NULLIF("{col}", \'\') AS {dtype.upper()})'
            casts.append(f'{expr} AS "{col}"')
        ddl.append(f"CREATE OR REPLACE VIEW churn_retention.{name} AS\nSELECT "+",\n       ".join(casts)+f"\nFROM churn_retention.{name}_csv;")
        manifest={"fileLocations":[{"URIs":[f"s3://{bucket}/{key}"]}],
                  "globalUploadSettings":{"format":"CSV","delimiter":",","textqualifier":"\"","containsHeader":"true"}}
        write_json(manifest,ROOT/"quicksight/manifests"/f"{name}.json")
        dictionary.extend([f"\n## {name}\n",GRAINS[name]+f"\n\nKey: {', '.join(KEYS[name])}. Rows in bundled run: {len(frame):,}.\n",
                           "| Column | Athena view type | Nullable in this run | Meaning |\n|---|---|---|---|\n"])
        for x in columns:
            meaning=FIELD_MEANINGS.get(x["name"],x["name"].replace("_"," ").capitalize())
            dictionary.append(f"| {x['name']} | {x['type']} | {'Yes' if x['nullable'] else 'No'} | {meaning} |\n")
    (ROOT/"quicksight/athena_setup.sql").write_text("\n\n".join(ddl)+"\n",encoding="utf-8")
    (ROOT/"DATA_DICTIONARY.md").write_text("".join(dictionary),encoding="utf-8")
    write_json(contracts,ROOT/"quicksight/dataset_contracts.json")
    print(f"Exported {len(contracts)} dataset contracts, Athena views and S3 manifests.")
    return contracts

